"""Golden single-process fixture: the scheduled run's records, pinned byte for byte.

Three tiny fixed-policy runs on CPU (arms A = adamw, F = adam_frozen, P = adamw_prewarmed), 3
steps, monitor and scoring diagnostics at every step, evaluation at the last step, update
scalars and provenance hashes on. The fixture files hold every record file the run writes, with
the volatile fields removed by ``normalize`` (below). The fixture is written once, on the
single-process code, and is never regenerated by a test run; to rewrite it on purpose set
``GOLDEN_REGENERATE=1``.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import pytest
import torch
from test_schedule import scheduled
from test_train import env as env  # noqa: F401  (the fixture)
from test_train import prepare

from zero_field_refusal.schedule import run_scheduled

FIXTURES = Path(__file__).parent / "fixtures" / "golden_single"
ARMS = {"A": "adamw", "F": "adam_frozen", "P": "adamw_prewarmed"}
RECORDS = ("metrics", "monitor", "evaluations", "diagnostics", "update_scalars",
           "chunk_checks", "cache_checks")  # fmt: skip
OVERRIDES = ("train.steps=3", "schedule.evaluate_at=[3]", "eval.monitor.every=1",
             "eval.diagnostics.every=1", "tracking.update_scalars=true",
             "tracking.provenance_hashes=true", "optimizer.lr=1e-3")  # fmt: skip

VOLATILE_PARTS = ("time", "seconds", "elapsed", "written_at", "timestamp", "run_id")
VOLATILE_KEYS = {
    "path", "hardware", "python", "packages", "git", "wandb", "host", "argv", "cwd", "dir",
    "started_at", "finished_at", "created", "version_info",
    "torch", "transformers", "cuda", "cudnn", "device_name",
}  # fmt: skip


def normalize(value: Any, dropped: set[str] | None = None) -> Any:
    """Drop what differs between two runs of the same code: every key containing time,
    seconds, elapsed, written_at, timestamp or run_id, and the keys in ``VOLATILE_KEYS``
    (absolute paths, machine, package and git identity, the path-check fingerprint's library and
    device versions). ``dropped`` collects the names removed."""
    if isinstance(value, dict):
        out = {}
        for key, item in value.items():
            if key in VOLATILE_KEYS or any(part in key.lower() for part in VOLATILE_PARTS):
                if dropped is not None:
                    dropped.add(key)
                continue
            out[key] = normalize(item, dropped)
        return out
    if isinstance(value, list):
        return [normalize(item, dropped) for item in value]
    return value


def lines(path: Path) -> list[str]:
    assert path.exists(), f"expected record file missing: {path.name}"
    rows = [json.dumps(normalize(json.loads(line)), sort_keys=True)
            for line in path.read_text().splitlines()]  # fmt: skip
    assert rows, f"expected record file empty: {path.name}"
    return rows


def snapshot(run_dir: Path) -> dict[str, list[str]]:
    out = {name: lines(run_dir / f"{name}.jsonl") for name in RECORDS}
    out["observations/measurements"] = lines(run_dir / "observations" / "measurements.jsonl")
    responses = sorted((run_dir / "responses").glob("*.jsonl"))
    assert responses, "no responses/*.jsonl written"
    for file in responses:
        out[f"responses/{file.stem}"] = lines(file)
    for name in ("terminal", "summary"):
        file = run_dir / f"{name}.json"
        assert file.exists(), f"expected record file missing: {file.name}"
        out[name] = [json.dumps(normalize(json.loads(file.read_text())), sort_keys=True)]
    meta = json.loads((run_dir / "meta.json").read_text())
    out["inputs"] = [json.dumps(normalize(meta.get("inputs", {})), sort_keys=True)]
    return out


@pytest.mark.parametrize("arm", ARMS)
def test_single_process_records_are_pinned(arm, env, tmp_path) -> None:  # noqa: F811
    # The fixture is pinned in a process with no visible CUDA device; a visible one changes the
    # CPU records in the last digits, which would read as a code change.
    assert not torch.cuda.is_available(), "run the golden test with CUDA_VISIBLE_DEVICES="
    torch.set_num_threads(1)
    extra = ("optimizer.preconditioner.batches=3",) if arm != "A" else ()
    checkpoint = f"tracking.endpoint_checkpoint={tmp_path / 'endpoint.pt'}"
    cfg = scheduled(
        tmp_path, f"optimizer={ARMS[arm]}", *OVERRIDES, checkpoint, *extra, policy="short"
    )
    prepare(env, cfg, "kl_monitor", *(("preconditioner",) if arm != "A" else ()))
    got = snapshot(run_scheduled(cfg, env, run_id=f"golden-{arm}"))
    assert got["metrics"] and got["monitor"] and got["evaluations"] and got["inputs"]
    path = FIXTURES / f"{arm}.json"
    if os.environ.get("GOLDEN_REGENERATE") == "1":
        path.write_text(json.dumps(got, indent=1, sort_keys=True) + "\n")
    assert path.exists(), "fixture missing: create it once with GOLDEN_REGENERATE=1"
    assert got == json.loads(path.read_text())
