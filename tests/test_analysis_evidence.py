REPO = Path(__file__).resolve().parents[1]
FIXTURE = REPO / "tests" / "fixtures" / "evidence"
RUNS_ROOT = FIXTURE / "runs"
EXPERIMENT = "evidence_fixture"
JUDGE = "wildguard"
SCRIPT = REPO / "scripts" / "build_analysis.py"

EXCLUDED = {
    "adamw-token-count_lr3e-05_s0": "unknown_arm",
    "adamw_lr1e-05_s1": "incomplete_labels",
    "adamw_lr3e-05_s2": "judge_identity",
    "sgd_lr0.03_s0": "not_completed",
}
OUTPUTS = ["arms.csv", "cells.csv", "estimates.csv", "exclusions.csv", "figure.svg",
           "manifest.json", "results.json", "runs.csv"]  # fmt: skip


def identity() -> dict:
    return judge_identity(load_config(f"judge/{JUDGE}"))


def collect(root: Path = RUNS_ROOT):
    return collect_runs(root, EXPERIMENT, JUDGE, identity())


def copy_fixture(tmp_path: Path) -> Path:
    root = tmp_path / "runs"
    shutil.copytree(RUNS_ROOT, root)
    return root


def read_csv(path: Path, **kwargs) -> pd.DataFrame:
    """A CSV table with every float read back exactly."""
    return pd.read_csv(path, float_precision="round_trip", **kwargs)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


# --- the runs table -----------------------------------------------------------------------------


def test_the_fixture_gives_the_expected_runs_table_and_exclusions() -> None:
    evidence = collect()
    expected = validate_runs(read_csv(FIXTURE / "expected_runs.csv"))
    pd.testing.assert_frame_equal(evidence.runs, expected, check_exact=True)

    considered = evidence.considered.set_index("run_id")
    run_dirs = sorted(p.name for p in (RUNS_ROOT / EXPERIMENT).iterdir())
    assert sorted(considered.index) == run_dirs  # every run directory, failed ones included
    excluded = considered[~considered["included"]]
    assert excluded["reason"].to_dict() == EXCLUDED
    assert set(considered.index[considered["included"]]) == set(expected["run_id"])
    assert (considered.loc[considered["included"], "reason"] == "").all()

    assert considered.loc["sgd_lr0.03_s0", "status"] == "failed"
    assert considered.loc["sgd_lr0.03_s0", "arm"] == "sgd"  # still placed in its cell
    assert considered.loc["adamw-token-count_lr3e-05_s0", "arm"] == (
        "adamw+token_count_normalization"
    )
    assert "2 of 10" in considered.loc["adamw_lr1e-05_s1", "detail"]
    assert "1 of 10" in considered.loc["adamw_lr3e-05_s2", "detail"]
    assert "rubric" in considered.loc["adamw_lr3e-05_s2", "detail"]


def test_every_file_read_is_hashed() -> None:
    evidence = collect()
    meta = f"{EXPERIMENT}/sgd_lr0.03_s0/meta.json"
    assert evidence.files[meta] == sha256(RUNS_ROOT / meta)
    labels = f"{EXPERIMENT}/adamw_lr3e-05_s0/judge/{JUDGE}.jsonl"
    assert evidence.files[labels] == sha256(RUNS_ROOT / labels)
    assert all((RUNS_ROOT / path).is_file() for path in evidence.files)
    assert list(evidence.files) == sorted(evidence.files)


