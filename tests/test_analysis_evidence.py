def _drop_file(_: list[dict]) -> None:
    return None


def _stray(records: list[dict]) -> list[dict]:
    return [*records, records[0] | {"item_id": "trained/judged:99"}]


def _conflict(records: list[dict]) -> list[dict]:
    other = "refusal" if records[0]["label"] != "refusal" else "harmful_compliance"
    return [*records, records[0] | {"label": other}]


def _retried(records: list[dict]) -> list[dict]:
    # An unparseable answer, written and then retried: the later labeled record counts.
    return [records[0] | {"label": None, "fields": None, "raw_output": "?"}, *records]


@pytest.mark.parametrize(
    ("edit", "reason"),
    [(_drop_file, "no_labels"), (_stray, "invalid_labels"), (_conflict, "invalid_labels"),
     (_retried, "")],
)  # fmt: skip
def test_label_files_are_checked_record_by_record(tmp_path, edit, reason) -> None:
    root = copy_fixture(tmp_path)
    path = root / EXPERIMENT / "sgd_lr0.01_s0" / "judge" / f"{JUDGE}.jsonl"
    records = edit([json.loads(line) for line in path.read_text().splitlines()])
    if records is None:
        path.unlink()
    else:
        path.write_text("".join(json.dumps(record) + "\n" for record in records))
    considered = collect(root).considered.set_index("run_id")
    assert considered.loc["sgd_lr0.01_s0", "reason"] == reason
    assert considered.loc["sgd_lr0.01_s0", "included"] == (reason == "")


# --- the rebuild --------------------------------------------------------------------------------


def run_script(out: Path) -> subprocess.CompletedProcess:
    command = [sys.executable, str(SCRIPT), str(RUNS_ROOT), "--experiment", EXPERIMENT,
               "--judge", JUDGE, "--out", str(out), "--seed", "7"]  # fmt: skip
    return subprocess.run(command, capture_output=True, text=True, cwd=REPO)


@pytest.fixture(scope="module")
def builds(tmp_path_factory) -> tuple[Path, Path]:
    """Two builds from the same inputs, in separate processes and directories."""
    root = tmp_path_factory.mktemp("builds")
    outs = root / "first", root / "nested" / "second"
    for out in outs:
        done = run_script(out)
        assert done.returncode == 0, done.stderr
    return outs


def test_a_rebuild_is_byte_identical_except_created_at(builds) -> None:
    first, second = builds
    assert sorted(p.name for p in first.iterdir()) == OUTPUTS
    assert sorted(p.name for p in second.iterdir()) == OUTPUTS
    for name in OUTPUTS:
        if name != "manifest.json":
            assert (first / name).read_bytes() == (second / name).read_bytes(), name
    manifests = [json.loads((out / "manifest.json").read_text()) for out in builds]
    created = [manifest.pop("created_at") for manifest in manifests]
    assert all(created)
    assert manifests[0] == manifests[1]


def test_the_build_records_runs_results_and_provenance(builds) -> None:
    out = builds[0]
    runs = pd.read_csv(out / "runs.csv")
    assert runs["run_id"].tolist() == sorted(runs["run_id"])
    excluded = runs[~runs["included"]]
    assert dict(zip(excluded["run_id"], excluded["reason"], strict=True)) == EXCLUDED
    exclusions = pd.read_csv(out / "exclusions.csv")
    assert dict(zip(exclusions["run_id"], exclusions["reason"], strict=True)) == EXCLUDED
    assert exclusions["detail"].notna().all()

    cells = pd.read_csv(out / "cells.csv", dtype={"seeds": str, "absent_seeds": str},
                        keep_default_na=False).set_index(["arm", "lr"])  # fmt: skip
    assert cells.loc[("adam_frozen", 3e-5), "seeds"] == "0 1"
    assert cells.loc[("adam_frozen", 3e-5), "absent_seeds"] == "2"
    assert cells.loc[("sgd", 0.01), "absent_seeds"] == ""

    results = json.loads((out / "results.json").read_text())
    settings = results["settings"]
    assert (settings["ci_method"], settings["level"], settings["resamples"], settings["seed"]) == (
        "percentile", 0.995, 4000, 7)  # fmt: skip
    analysis = results["analysis"]
    assert analysis["seeds"] == [0, 1, 2]
    assert analysis["decision"] in ("positive", "opposite", "equivalence", "inconclusive")
    assert analysis["h2"]["vs_sgd_label"] in ("different", "indistinguishable", "inconclusive")
    assert sorted(results["analyzed_runs"]) == sorted(
        pd.read_csv(FIXTURE / "expected_runs.csv")["run_id"]
    )
    k_star = analysis["selection"]["k_star"]
    assert analysis["selection"]["c_lo"] < k_star < analysis["selection"]["c_hi"]
    assert set(results["units"]) >= {"K", "h", "delta"}

    estimates = read_csv(out / "estimates.csv")
    primary = estimates[(estimates["quantity"] == "delta") & (estimates["level"] == "k_star")]
    assert len(primary) == 1
    row = primary.iloc[0]
    delta = analysis["primary"]["k_star"]
    assert (row["estimate"], row["ci_low"], row["ci_high"]) == (
        delta["estimate"], delta["ci_low"], delta["ci_high"])  # unrounded  # fmt: skip
    assert row["K"] == k_star
    arms = read_csv(out / "arms.csv").set_index("arm")
    assert arms.loc["adamw", "intercept"] == analysis["arms"]["adamw"]["intercept"]

    manifest = json.loads((out / "manifest.json").read_text())
    assert manifest["experiment"] == EXPERIMENT
    assert manifest["judge"]["name"] == JUDGE and manifest["judge"]["identity"] == identity()
    assert manifest["rng_seed"] == 7
    assert manifest["protocol_versions"] == [1]
    assert sorted(manifest["runs"]["considered"]) == sorted(runs["run_id"])
    assert set(manifest["runs"]["excluded"]) == set(EXCLUDED)
    for path, digest in manifest["inputs"].items():
        assert sha256(RUNS_ROOT / path) == digest, path
    assert f"{EXPERIMENT}/sgd_lr0.03_s0/meta.json" in manifest["inputs"]
    for name, digest in manifest["outputs"].items():
        assert sha256(out / name) == digest, name
    assert set(manifest["outputs"]) == set(OUTPUTS) - {"manifest.json"}
    assert set(manifest["code"]["git"]) == {"commit", "dirty"}
    assert str(RUNS_ROOT) not in (out / "manifest.json").read_text()  # no local paths

    figure = (out / "figure.svg").read_text()
    assert figure.startswith("<?xml") and "<svg" in figure


def test_the_output_directory_is_never_overwritten(builds) -> None:
    out = builds[0]
    before = {p.name: p.read_bytes() for p in out.iterdir()}
    done = run_script(out)
    assert done.returncode != 0
    assert "exists" in done.stderr
    assert {p.name: p.read_bytes() for p in out.iterdir()} == before


def test_a_failed_build_leaves_no_output_directory(tmp_path) -> None:
    out = tmp_path / "out"
    with pytest.raises(ValueError, match="no run directories"):
        build_analysis(RUNS_ROOT, "no_such_experiment", JUDGE, identity(), out)
    assert not out.exists()
    assert list(tmp_path.iterdir()) == []  # no partial directory either


