def test_seeds_are_shared_across_arms_and_the_bootstrap_draws_them_together() -> None:
    evidence = collect()
    runs = evidence.runs
    per_arm = runs.groupby("arm")["seed"].agg(lambda s: sorted(set(s))).to_dict()
    assert per_arm == {"adam_frozen": [0, 1, 2], "adamw": [0, 1, 2], "sgd": [0, 1, 2]}
    per_cell = runs.groupby(["arm", "lr"])["seed"].agg(lambda s: sorted(s)).to_dict()
    assert per_cell == {
        ("adam_frozen", 1e-5): [0, 1, 2], ("adam_frozen", 3e-5): [0, 1],  # missing run
        ("adamw", 1e-5): [0, 2],  # incomplete labels
        ("adamw", 3e-5): [0, 1],  # another judge's label
        ("sgd", 0.01): [0, 1, 2], ("sgd", 0.03): [1, 2],  # failed run
    }  # fmt: skip

    # Shared teacher: one training stream per seed, the same in every arm and cell.
    included = evidence.considered[evidence.considered["included"]]
    assert (included.groupby("seed")["training_stream"].nunique() == 1).all()
    assert included.groupby("seed")["training_stream"].first().nunique() == 3

    # A resample weights every run of a seed alike, whatever its arm or learning rate.
    resampling = paired_resampling(runs["seed"], resamples=50, seed=0)
    weights = resampling.run_weights(runs["seed"].to_numpy())
    for seed in (0, 1, 2):
        columns = weights[:, (runs["seed"] == seed).to_numpy()]
        assert (columns == columns[:, :1]).all()
        assert set(runs.loc[runs["seed"] == seed, "arm"]) == {"sgd", "adam_frozen", "adamw"}

    result = analyze(runs, select_k_star(runs), level=STAGE1_INTERVAL.level,
                     ci_method=STAGE1_INTERVAL.ci_method, resamples=200, seed=0)  # fmt: skip
    assert result.seeds == [0, 1, 2]
    assert result.runs_total == len(runs) == 14
    assert set(result.arms) == {"sgd", "adam_frozen", "adamw"}


def test_runs_of_one_seed_with_different_teacher_streams_stop_the_analysis(tmp_path) -> None:
    root = copy_fixture(tmp_path)
    path = root / EXPERIMENT / "adamw_lr3e-05_s1" / "meta.json"
    meta = json.loads(path.read_text())
    meta["inputs"]["streams"]["training"]["sha256"] = "0" * 64
    path.write_text(json.dumps(meta))
    with pytest.raises(ValueError, match="seed 1"):
        collect(root)


